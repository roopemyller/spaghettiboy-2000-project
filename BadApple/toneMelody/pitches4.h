void midi() {
  int index = 0;
  
  while (true) {
    uint8_t noteIdx = pgm_read_byte(&rle_packed[index]);
    uint8_t count = pgm_read_byte(&rle_packed[index + 1]);
    
    if (noteIdx == 0 && count == 0) break;  // End marker
    
    boolean isLong = (noteIdx >= 18);
    uint8_t baseIdx = isLong ? noteIdx - 18 : noteIdx;
    
    for (int j = 0; j < count; j++) {
      if (baseIdx == 17) {  // Delay
        delay(delayTime);
      } else {
        uint16_t freq = pgm_read_word(&noteTable[baseIdx]);
        if (isLong) {
          tone(tonePin, freq, longDur);
        } else {
          tone(tonePin, freq, dur);
        }
        delay(delayTime);
      }
    }
    
    index += 2;
  }
}